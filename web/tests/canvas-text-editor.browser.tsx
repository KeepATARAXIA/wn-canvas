import React, { useState } from "react";
import { createRoot } from "react-dom/client";
import { flushSync } from "react-dom";
import { CanvasTextEditor } from "../src/components/canvas/canvas-text-editor";
import { textContentHtml } from "../src/lib/canvas/text-rich-content";
import type { CanvasRichText } from "../src/types/canvas";
import "../src/styles/globals.css";

// Runs the real component in an isolated page. All data is held in memory.
export async function runCanvasTextEditorTests(mount: HTMLElement) {
    const results: string[] = [];
    let saved: { content: string; richText?: CanvasRichText } = { content: "片名：第二层皮肤\n时长：约 25 秒\n风格：极简未来感" };
    let reset: (content: string, richText?: CanvasRichText) => void;
    let reopen: () => void;
    let stopped = 0;
    const root = createRoot(mount);
    function Demo() {
        const [value, setValue] = useState(saved);
        const [editing, setEditing] = useState(true);
        reset = (content, richText) => { saved = { content, richText }; setValue(saved); setEditing(true); };
        reopen = () => setEditing(true);
        return <div data-node-id="fixture" style={{ position: "absolute", left: 180, top: 120, width: 600, height: 420, border: "1px solid #555", borderRadius: 12, background: "#242424" }}>
            {editing ? <CanvasTextEditor nodeId="fixture" {...value} className="h-full w-full p-4" style={{ color: "#f3f4f6", fontSize: 16, lineHeight: 1.8 }} references={[{ id: "ref", nodeId: "ref", kind: "text", title: "参考场景", label: "文本 1", text: "参考场景", active: true }]} onChange={(content, richText) => { saved = { content, richText }; setValue(saved); }} onStopEditing={() => { stopped++; setEditing(false); }} /> : <div className="canvas-rich-text p-4" style={{ color: "#f3f4f6" }} dangerouslySetInnerHTML={{ __html: textContentHtml(saved.content, saved.richText) }} />}
        </div>;
    }
    const tick = () => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve())));
    const assert = (condition: unknown, name: string) => { if (!condition) { const html = editor()?.innerHTML; editor()?.blur(); throw new Error(`${name}\n${JSON.stringify({ saved, html })}`); } results.push(name); };
    const editor = () => document.querySelector<HTMLElement>("[data-canvas-rich-editor]")!;
    const select = async (text: string) => {
        const element = editor();
        const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
        let found: Node | null;
        while ((found = walker.nextNode())) {
            const index = (found.nodeValue || "").indexOf(text);
            if (index < 0) continue;
            const range = document.createRange();
            range.setStart(found, index); range.setEnd(found, index + text.length);
            element.focus();
            const selection = window.getSelection()!;
            selection.removeAllRanges(); selection.addRange(range);
            document.dispatchEvent(new Event("selectionchange"));
            await tick();
            return;
        }
        throw new Error(`Cannot find selection: ${text}`);
    };
    const click = async (label: string) => {
        const button = document.querySelector<HTMLButtonElement>(`button[aria-label="${label}"]`) || Array.from(document.querySelectorAll<HTMLButtonElement>('button[role="menuitemradio"]')).find((item) => item.textContent === label);
        if (!button) throw new Error(`Missing button: ${label}`);
        button.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true }));
        button.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, cancelable: true }));
        button.click();
        await tick();
    };
    flushSync(() => root.render(<Demo />));
    await tick();
    await select("第二层皮肤");
    assert(Boolean(document.querySelector('[role="toolbar"][aria-label="文本格式"]')), "selection opens formatting toolbar");
    await click("加粗");
    assert(editor().querySelector("b,strong")?.textContent === "第二层皮肤", "bold affects only selected substring");
    assert(window.getSelection()?.toString() === "第二层皮肤", "toolbar click retains selection");
    await click("斜体"); await click("下划线"); await click("删除线");
    assert(Boolean(editor().querySelector("i,em")) && Boolean(editor().querySelector("u")) && Boolean(editor().querySelector("strike,s")), "inline formats compose");
    assert(saved.content === "片名：第二层皮肤\n时长：约 25 秒\n风格：极简未来感", "formatting keeps plain content clean");
    const formatted = saved.richText;
    document.execCommand("undo"); await tick();
    assert(!editor().querySelector("strike,s"), "native undo removes last formatting change");
    document.execCommand("redo"); await tick();
    assert(Boolean(editor().querySelector("strike,s")), "native redo restores formatting");
    const sameEditor = editor();
    await click("放大编辑文本");
    assert(editor() === sameEditor && window.getSelection()?.toString() === "第二层皮肤", "expand keeps editor DOM and selection");
    await click("收起编辑");
    assert(editor() === sameEditor && window.getSelection()?.toString() === "第二层皮肤", "collapse keeps editor DOM and selection");
    document.execCommand("undo"); await tick();
    assert(!editor().querySelector("strike,s"), "undo survives expand and collapse");
    document.execCommand("redo"); await tick();
    await click("放大编辑文本");
    const backdropPress = new MouseEvent("mousedown", { bubbles: true, cancelable: true });
    document.querySelector(".canvas-text-editor-expanded")!.dispatchEvent(backdropPress);
    assert(backdropPress.defaultPrevented && document.activeElement === editor(), "full screen background keeps keyboard focus in editor");
    document.querySelector<HTMLButtonElement>('button[aria-label="关闭放大编辑"]')!.focus();
    await click("关闭放大编辑");
    assert(document.activeElement === editor() && window.getSelection()?.toString() === "第二层皮肤", "closing full screen restores editing focus and selection");
    await click("正文或标题"); await click("标题 2");
    assert(editor().querySelector("h2")?.textContent === "片名：第二层皮肤", "heading applies to selected paragraph only");
    await click("正文或标题"); await click("正文");
    assert(!editor().querySelector("h1,h2,h3"), "heading can return to body text");
    flushSync(() => reset("标题文字")); await tick(); await select("标题文字");
    await click("正文或标题"); await click("标题 2"); await click("加粗");
    const normalHeading = saved;
    flushSync(() => reset("Temporary")); await tick();
    flushSync(() => reset(normalHeading.content, normalHeading.richText)); await tick();
    assert(editor().querySelector("h2 span")?.getAttribute("style") === "font-weight: normal;", "unbold heading selection survives reloading saved content");
    flushSync(() => reset("One\nTwo")); await tick();
    const all = document.createRange(); all.selectNodeContents(editor());
    window.getSelection()!.removeAllRanges(); window.getSelection()!.addRange(all);
    document.dispatchEvent(new Event("selectionchange")); await tick();
    await click("无序列表");
    assert(editor().querySelectorAll("ul li").length === 2 && saved.content === "• One\n• Two", "bulleted list saves clean marked text");
    await click("有序列表");
    assert(editor().querySelectorAll("ol li").length === 2 && saved.content === "1. One\n2. Two", "numbered list replaces bullet list");
    await click("有序列表");
    assert(!editor().querySelector("ol,ul"), "list formatting can be removed");
    flushSync(() => reset("Safe")); await tick(); await select("Safe");
    const transfer = new DataTransfer();
    transfer.setData("text/html", '<p onclick="bad()"><b>Pasted</b><img src=x onerror="bad()"><script>bad()</script></p>');
    editor().dispatchEvent(new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData: transfer }));
    await tick();
    assert(saved.content === "Pasted" && !editor().querySelector("script,img,[onclick]") && Boolean(editor().querySelector("b,strong")), "paste keeps supported formatting and removes unsafe HTML");
    flushSync(() => reset("甲乙")); await tick(); await select("甲");
    window.getSelection()!.collapseToEnd();
    const plainTransfer = new DataTransfer(); plainTransfer.setData("text/plain", "测试");
    editor().dispatchEvent(new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData: plainTransfer })); await tick();
    assert(saved.content === "甲测试乙" && editor().children.length === 1, "single line plain paste stays within current paragraph");
    flushSync(() => reset("@参考")); await tick(); await select("@参考");
    window.getSelection()!.collapseToEnd();
    editor().dispatchEvent(new PointerEvent("pointerup", { bubbles: true })); await tick();
    const option = document.querySelector<HTMLButtonElement>('[role="option"]');
    assert(option?.textContent === "文本 1参考场景", "resource mention suggestions remain available");
    option!.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, cancelable: true })); option!.click(); await tick();
    assert(saved.content === "文本 1 ", "resource mention replaces query without losing text");
    flushSync(() => reset("Plain")); await tick();
    editor().dispatchEvent(new CompositionEvent("compositionstart", { bubbles: true, data: "" }));
    editor().textContent = "中文输入";
    editor().dispatchEvent(new InputEvent("input", { bubbles: true, isComposing: true, inputType: "insertCompositionText", data: "中文输入" }));
    const outside = document.getElementById("result")!;
    outside.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true })); await tick();
    assert(saved.content === "中文输入" && stopped > 0 && !editor(), "outside click saves pending composition before leaving editor");
    flushSync(() => reopen()); await tick();
    assert(editor().textContent === "中文输入", "saved composition reopens correctly");
    flushSync(() => reset("Preview", { version: 1, text: "Old", html: "<h1>Old</h1>" })); await tick();
    assert(editor().textContent === "Preview" && !editor().querySelector("h1"), "external text replacement drops stale format snapshot");
    flushSync(() => reset("片名：第二层皮肤\n时长：约 25 秒\n风格：极简未来感", formatted)); await tick();
    assert(Boolean(editor().querySelector("b,strong")), "format survives closing and reopening the editor");
    await select("第二层皮肤");
    await click("正文或标题"); await click("标题 2");
    const savedFinal = saved;
    outside.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true })); await tick();
    return { passed: results.length, tests: results, saved: savedFinal };
}
